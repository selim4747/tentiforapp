import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const manifest = read('uygulama/kabuk/android/app/src/main/AndroidManifest.xml');
const activity = read('uygulama/kabuk/android/app/src/main/java/dev/pages/tentiforapp/MainActivity.java');
const strings = read('uygulama/kabuk/android/app/src/main/res/values/strings.xml');
const plugin = read('uygulama/kabuk/android/app/src/main/java/dev/pages/tentiforapp/TentiforNativePlugin.java');
const widget = read('uygulama/kabuk/android/app/src/main/java/dev/pages/tentiforapp/TentiforWidgetProvider.java');
const workflow = read('.github/workflows/android-build.yml');
const nativeBridge = read('js/core/100-v60-native.js');
const capacitor = JSON.parse(read('uygulama/kabuk/capacitor.config.json'));

assert.match(manifest, /android\.permission\.USE_BIOMETRIC/);
assert.match(manifest, /android\.intent\.action\.SEND/);
assert.match(manifest, /TentiforWidgetProvider/);
assert.match(manifest, /default_notification_channel_id/);
assert.match(manifest, /default_notification_icon/);
assert.match(activity, /registerPlugin\(TentiforNativePlugin\.class\)/);
assert.match(activity, /ACTION_SEND/);
assert.match(activity, /onBackPressed\(\)/);
assert.match(activity, /tentifor-back-button/);
assert.match(activity, /NotificationChannel/);
assert.match(activity, /createNotificationChannel/);
assert.match(activity, /"tentiforapp"/);
assert.match(strings, /default_notification_channel_id.*tentiforapp/);
assert.match(plugin, /@CapacitorPlugin\(name = "TentiforNative"\)/);
assert.match(plugin, /saveAppState/);
assert.match(plugin, /loadAppState/);
assert.match(plugin, /tentiforapp-state\.json/);
assert.match(plugin, /BiometricPrompt/);
assert.match(plugin, /FLAG_KEEP_SCREEN_ON/);
assert.match(widget, /AppWidgetProvider/);
assert.match(nativeBridge, /TentiforNative6/);
assert.match(workflow, /assembleDebug/);
assert.match(workflow, /upload-artifact@v4/);
assert.match(workflow, /Offline APK shell verified/);
assert.match(workflow, /assets\/public\/js\/core\/125-live-site-bootstrap\.js/);
assert.equal(capacitor.server.url, undefined, 'APK ilk olarak bundled local web shell’i açmalı; offline cold start yerel kalmalı');
assert.equal(capacitor.server.cleartext, false, 'uzak site yalnızca HTTPS kullanmalı');
assert.ok(capacitor.server.allowNavigation.includes('tentifor.com'));
assert.ok(capacitor.server.allowNavigation.includes('www.tentifor.com'));
console.log('Android native contracts: PASS (local offline shell, live HTTPS navigation, Capacitor plugin, biometric, widget, intents and CI)');
